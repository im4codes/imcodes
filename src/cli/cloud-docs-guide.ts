export function getCloudDocsGuideText(topic: string = 'index'): { ok: true; topic: CloudDocsGuideTopic; text: string } | { ok: false; message: string } {
  const normalized = topic.trim().toLowerCase() || 'index';
  if (!isCloudDocsGuideTopic(normalized)) {
    return {
      ok: false,
      message: `Unknown docs topic "${topic}". Valid topics: ${CLOUD_DOCS_GUIDE_TOPICS.join(', ')}`,
    };
  }
  if (normalized === 'all') {
    const sections = CLOUD_DOCS_GUIDE_TOPICS
      .filter((item): item is Exclude<CloudDocsGuideTopic, 'all' | 'index'> => item !== 'all' && item !== 'index')
      .map((item) => GUIDE_SECTIONS[item]);
    return {
      ok: true,
      topic: 'all',
      text: `${GUIDE_SECTIONS.index}\n\n---\n\n${sections.join('\n\n---\n\n')}`,
    };
  }
  return {
    ok: true,
    topic: normalized,
    text: GUIDE_SECTIONS[normalized],
  };
}
