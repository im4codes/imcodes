import { cleanup, fireEvent, render, waitFor, within } from '@testing-library/preact';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { TaskPairBrief } from '../../src/components/TaskPairBrief.js';
import { receiveTaskPairBrief, requestTaskPairBrief, resetTaskPairBriefStoreForTests, setTaskPairBriefRequester, taskPairBriefStatus } from '../../src/task-pair-brief-store.js';
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }));
vi.mock('../../src/components/ChatMarkdown.js', () => ({ ChatMarkdown: ({ text }: { text: string }) => <div class="markdown">{text}</div> }));
const brief = `${'Long explanation\n'.repeat(100)}\n- [x][ ] First\n- [x][x] Second\n- [ ] Legacy\n\`\`\`md\n- [x][x] not a real item\n\`\`\``;
const toggle = (container: HTMLElement) => within(container).getByRole('button', { name: 'taskPair.checklist_toggle' });
beforeEach(() => resetTaskPairBriefStoreForTests());
afterEach(() => { cleanup(); resetTaskPairBriefStoreForTests(); vi.restoreAllMocks(); });
describe('independent pair checklist', () => {
  it('opens numbered real dual/single checklist before long explanation, without opening markdown', () => {
    const v = render(<TaskPairBrief taskId="a" brief={brief} />);
    fireEvent.click(toggle(v.container));
    expect(v.container.querySelector('.markdown')).toBeNull();
    const panel = v.container.querySelector('.task-pair-brief-checklist-panel')!;
    expect(panel.textContent).toContain('1. First');
    expect(panel.textContent).toContain('3. Legacy');
    expect(panel.textContent).not.toContain('not a real item');
    expect(panel.querySelectorAll('input')).toHaveLength(5);
    expect([...panel.querySelectorAll('input')].map(el => el.checked)).toEqual([true, false, true, true, false]);
    expect([...panel.querySelectorAll('input')].every(el => el.disabled)).toBe(true);
    expect(within(v.container).getByLabelText('taskPair.checklist_no_audit')).toBeTruthy();
    fireEvent.click(within(v.container).getByRole('button', { name: 'taskPair.brief_expand' }));
    expect(v.container.querySelector('.markdown')?.textContent).toContain('Long explanation');
    expect(v.container.querySelectorAll('.task-pair-brief-checklist')).toHaveLength(1);
    const regions = [...v.container.querySelectorAll('[role="region"]')];
    expect(regions[0]).toBe(panel);
    fireEvent.click(toggle(v.container));
    expect(v.container.querySelector('.markdown')).toBeTruthy();
    expect(v.container.querySelector('.task-pair-brief-checklist-panel')).toBeNull();
  });
  it('deduplicates lazy fetch across two mounted copies, brief/copy/checklist and reopening', async () => {
    const request = vi.fn(); setTaskPairBriefRequester(request);
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } });
    const a = render(<TaskPairBrief taskId="a" briefRevision="r1" />);
    const b = render(<TaskPairBrief taskId="a" briefRevision="r1" />);
    expect(request).not.toHaveBeenCalled();
    fireEvent.click(toggle(a.container)); fireEvent.click(toggle(b.container));
    fireEvent.click(within(a.container).getByRole('button', { name: 'taskPair.brief_expand' }));
    fireEvent.click(within(a.container).getByRole('button', { name: 'taskPair.brief_copy' }));
    expect(request).toHaveBeenCalledTimes(1);
    receiveTaskPairBrief('a', 'r1', brief);
    await waitFor(() => expect(writeText).toHaveBeenCalledWith(brief));
    await waitFor(() => expect(b.container.querySelectorAll('.task-pair-brief-checklist-row')).toHaveLength(3));
    fireEvent.click(toggle(b.container)); fireEvent.click(toggle(b.container));
    expect(request).toHaveBeenCalledTimes(1);
  });
  it('keeps new revision loading when an old answer arrives, then displays new states', async () => {
    const request = vi.fn(); setTaskPairBriefRequester(request);
    const v = render(<TaskPairBrief taskId="a" briefRevision="old" />);
    fireEvent.click(toggle(v.container));
    v.rerender(<TaskPairBrief taskId="a" briefRevision="new" />);
    receiveTaskPairBrief('a', 'old', '- [ ][ ] Stale');
    expect(taskPairBriefStatus('new')).toBe('loading');
    requestTaskPairBrief('a', 'new');
    expect(request).toHaveBeenCalledTimes(2);
    expect(v.container.textContent).not.toContain('Stale');
    receiveTaskPairBrief('a', 'new', '- [x][x] Fresh');
    await waitFor(() => expect(v.container.textContent).toContain('1. Fresh'));
    expect([...v.container.querySelectorAll('input')].every(el => el.checked)).toBe(true);
  });
  it('shows fetch failure and retries on reopen without exposing stale rows', async () => {
    const request = vi.fn(); setTaskPairBriefRequester(request);
    const v = render(<TaskPairBrief taskId="a" briefRevision="missing" />);
    fireEvent.click(toggle(v.container)); receiveTaskPairBrief('a', null, null);
    await waitFor(() => expect(v.container.textContent).toContain('taskPair.brief_unavailable'));
    fireEvent.click(toggle(v.container)); fireEvent.click(toggle(v.container));
    expect(request).toHaveBeenCalledTimes(2);
    receiveTaskPairBrief('a', 'missing', '');
    await waitFor(() => expect(v.container.textContent).toContain('taskPair.checklist_empty'));
  });
  it('handles zero and 101 rows and live inline state updates without dropping the first item', () => {
    const v = render(<TaskPairBrief taskId="a" brief="No tasks" />);
    fireEvent.click(toggle(v.container));
    expect(v.container.textContent).toContain('taskPair.checklist_empty');
    const rows = Array.from({ length: 101 }, (_, i) => `- [ ][ ] Task ${i}`).join('\n');
    v.rerender(<TaskPairBrief taskId="a" brief={rows} />);
    expect(v.container.querySelectorAll('.task-pair-brief-checklist-row')).toHaveLength(101);
    v.rerender(<TaskPairBrief taskId="a" brief={rows.replace('[ ][ ]', '[x][x]')} />);
    expect(v.container.querySelector('input')?.checked).toBe(true);
  });
  it('does not carry open/copy state to a different task or keyed server/scope', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } });
    setTaskPairBriefRequester(() => {});
    const v = render(<TaskPairBrief key="server1" taskId="a" briefRevision="old" />);
    fireEvent.click(toggle(v.container));
    fireEvent.click(within(v.container).getByRole('button', { name: 'taskPair.brief_copy' }));
    v.rerender(<TaskPairBrief key="server2" taskId="a" brief="- [x][x] Server 2" />);
    receiveTaskPairBrief('a', 'old', '- [ ][ ] Old scope');
    expect(v.container.querySelector('.task-pair-brief-checklist-panel')).toBeNull();
    await Promise.resolve(); expect(writeText).not.toHaveBeenCalled();
    fireEvent.click(toggle(v.container)); expect(v.container.textContent).toContain('Server 2');
    v.rerender(<TaskPairBrief key="server2" taskId="b" brief="- [ ][ ] Task B" />);
    expect(v.container.querySelector('.task-pair-brief-checklist-panel')).toBeNull();
  });
  it('has unique controlled IDs for repeated task mounts and stops click navigation', () => {
    const navigate = vi.fn();
    const v = render(<div onClick={navigate}><TaskPairBrief taskId="a" brief={brief} /><TaskPairBrief taskId="a" brief={brief} /></div>);
    const buttons = within(v.container).getAllByRole('button', { name: 'taskPair.checklist_toggle' });
    expect(new Set(buttons.map(el => el.getAttribute('aria-controls'))).size).toBe(2);
    buttons.forEach(el => fireEvent.click(el));
    expect(v.container.querySelectorAll('.task-pair-brief-checklist-panel')).toHaveLength(2);
    expect(navigate).not.toHaveBeenCalled();
  });
});
